  function stop() {
    generation++;
    player.onended = player.onerror = null;
    player.pause();
    const wasSpeaking = speaking;
    speaking = false;
    who = '';
    words = '';
    if (wasSpeaking) changed();
  }
  function play(speaker, text) {
    stop();
    const playlist = resolve(speaker, text);
    if (!playlist.length || !volume() || document.hidden) return 0;
    const token = generation;
    let next = 0;
    speaking = true;
    who = speaker;
    words = text;
    changed();
    function stopCurrent() {
      if (token === generation) stop();
    }
    function advance() {
      if (token !== generation) return;
      if (next === playlist.length) {
        stop();
        return;
      }
      const take = playlist[next++];
      player.src = './assets/voice/' + take.file + '.mp3' + soundRevision;
      player.volume = volume();
      player.muted = false;
      player.onended = advance;
      player.onerror = stopCurrent;
      player.play().catch(stopCurrent);
    }
    advance();
    return totalSeconds(playlist);
  }
