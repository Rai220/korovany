function settle() {
  for (const person of residents) {
    const [x, z] = person.home,
      a = spawnAt(person.kind, 'civilian', x, z, person.id);
    a.homeX = a.x;
    a.homeZ = a.z;
    a.stop = 3 + a.id * 0.2;
    a.legIndex = 0;
  }
}
function wander(a, dt) {
  if (distance(a, game) > 43) return;
  if (distance(a, game) < 2.75) {
    a.angle = Math.atan2(wrapped(game.x - a.x), wrapped(game.z - a.z));
    return;
  }
  if (a.stop > 0) {
    a.stop -= dt;
    return;
  }
  const offsets = [
      [2.5, 1.2],
      [2.1, -1.1],
      [-1, 1.1],
      [0, 0],
    ],
    v = offsets[a.legIndex % 4],
    dest = point(a.homeX + v[0], a.homeZ + v[1]);
  if (distance(a, dest) < 0.42) {
    a.stop = 4 + (a.id % 4);
    a.legIndex++;
    a.path = null;
    return;
  }
  advance(a, dest, 0.86, dt);
}
function visitResident(a) {
  const npc = residents.find((n) => n.id === a.tag),
    s = game.story;
  if (a.tag === 'healer') {
    if (s.herbs === 'gathered') {
      s.herbs = 'done';
      game.bandages += 3;
      game.health = Math.min(100, game.health + 25);
      s.entries.push(['Три перевязи', 'Мара сделала три чистых бинта из принесённого тысячелистника.']);
      checkpoint();
      speak(npc.name, 'Вода кипела, пока ты ходил. Вот три чистых перевязи.');
      return;
    }
    if (!s.herbs) {
      scene(
        'Лесной союз · Просьба',
        'Белая трава',
        1,
        npc.name,
        'Мне хватит трёх стеблей. Только бери те, что у межевого камня к юго-востоку от поселения. Дальше земля уже тянет железо, на ней трава горчит.',
        [
          [
            'Принести тысячелистник',
            () => {
              s.herbs = 'seek';
              s.entries.push([
                'Белая трава',
                'Соберите тысячелистник у межевого камня на юго-востоке лесного посёлка. На карте место отмечено крестом.',
              ]);
              checkpoint();
            },
          ],
          ['В другой раз', () => {}],
        ],
      );
      return;
    }
  }
  speak(npc.name, npc.lines[(a.talks || 0) % npc.lines.length]);
  a.talks = (a.talks || 0) + 1;
}
function gatherHerb() {
  game.story.herbs = 'gathered';
  game.story.entries.push(['Тысячелистник', 'Отнесите стебли травнице Маре в лесное поселение.']);
  checkpoint();
  notify('Собран тысячелистник · Вернитесь к Маре');
}
