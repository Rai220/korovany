const ladder = { x: -59, z: 58.6 };
function watchHeight(x, z) {
  if ((Math.abs(x + 59) < 2.08 || Math.abs(x + 41) < 2.08) && Math.abs(z - 56) < 1.86) return 4.62;
  if (x >= -57.2 && x <= -42.8 && Math.abs(z - 56) < 0.78)
    return 4.62 - 0.66 * Math.sin(Math.PI * clamp((x + 57) / 14, 0, 1));
  return 0;
}
